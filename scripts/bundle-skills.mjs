import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

const sources = [
  "SKILL.md",
  "SKILL (1).md",
  "SKILL (2).md",
  "SKILL (3).md",
  path.join(".cursor", "skills", "portfolio-design", "SKILL.md"),
  path.join(".cursor", "skills", "portfolio-design", "typography.md"),
  path.join(".cursor", "skills", "portfolio-design", "color-palettes.md"),
  path.join(".cursor", "skills", "portfolio-design", "layout-patterns.md"),
  path.join(".cursor", "skills", "portfolio-design", "anti-patterns.md"),
];

const chunks = [];

for (const rel of sources) {
  const full = path.join(root, rel);
  if (!fs.existsSync(full)) continue;
  const text = fs.readFileSync(full, "utf8");
  chunks.push(`### Source: ${rel}\n\n${text}`);
}

const combined = chunks.join("\n\n---\n\n");

const out = `// Auto-generated by scripts/bundle-skills.mjs — do not edit manually
export const BUNDLED_SKILL_CONTENT = ${JSON.stringify(combined)};
`;

fs.writeFileSync(path.join(root, "lib", "ai", "bundled-skills.ts"), out);
console.log(`Bundled ${chunks.length} skill files (${combined.length} chars)`);
